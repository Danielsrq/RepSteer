"""Build a CONDITIONAL LoReFT dataset: animal -> emoji, everything else -> normal prose.

The previous emoji LoReFT was unconditional ("always answer in emoji"). This one has to learn
the condition too, so the negatives matter: non-animal prompts (including the lexical decoys
like "the Python programming language") are paired with ordinary prose targets.

  animal targets : the system-prompt answers already generated by the ceiling run
                   (data/wsp/degen_precheck2.json, mean 9-13 unique glyphs)
  other targets  : fresh plain-model generations (no system prompt, no edit)

Held out from training: animal_test / other_test / the v2 adversarial sets.

  .venv/bin/python scripts/wsp/build_cond_dataset.py
"""
import json, os, sys
import torch
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import common
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "emoji"))
from train_loreft import clean, glyphs

OUT = "data/reft/mine/emoji_conditional.json"


def main():
    P = json.load(open("data/wsp/cond_prompts.json"))
    H = json.load(open("data/wsp/lexical_control.json"))
    PC = json.load(open("data/wsp/degen_precheck2.json"))
    ceil = {r["prompt"]: r for r in PC["table"]}

    # animal positives: ceiling answers, but ONLY for prompts not reserved for evaluation
    heldout = set(P["animal_test"]) | set(P["other_test"])
    pos = [{"context": q, "target": r["ceil_text"]}
           for q, r in ceil.items()
           if q not in heldout and r["ceil_div"] > 0.5 and len(glyphs(r["ceil_text"])) >= 4]
    print(f"animal positives: {len(pos)} (ceiling answers, >=4 glyphs, fair prompts only)")

    # negatives: non-animal, including the lexical decoys
    neg_prompts = [q for q in P["other_train"] if q not in heldout] + H["animal_word_not_animal"]
    print(f"non-animal negatives to generate: {len(neg_prompts)}")

    mid, kind = common.resolve("qwen35-4b")
    print(f"Loading {mid} ...")
    handler, model, tok, is_mm = common.load_model(mid, kind)
    model.eval()
    dev = next(model.parameters()).device

    def gen(q, n=40):
        msgs = [{"role": "user", "content": q}]
        try:
            txt = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True,
                                          enable_thinking=False)
        except TypeError:
            txt = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        ids = torch.tensor([tok(txt, add_special_tokens=False).input_ids], device=dev)
        with torch.inference_mode():
            g = model.generate(input_ids=ids, max_new_tokens=n, do_sample=False,
                               pad_token_id=tok.eos_token_id)
        return clean(tok.decode(g[0, ids.shape[1]:], skip_special_tokens=True))

    neg = []
    for i, q in enumerate(neg_prompts):
        t = gen(q)
        if glyphs(t):
            print(f"  warn: emoji in a NEGATIVE target, dropping -> {q[:40]}")
            continue
        neg.append({"context": q, "target": t})
    print(f"non-animal negatives kept: {len(neg)}")

    data = pos + neg
    import random
    random.Random(0).shuffle(data)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(data, open(OUT, "w"), ensure_ascii=False, indent=1)
    print(f"\nsaved {OUT}: {len(data)} examples ({len(pos)} emoji / {len(neg)} prose)")
    print("\nsamples:")
    for e in data[:4]:
        print(f"  ctx: {e['context'][:52]}")
        print(f"  tgt: {e['target'][:62]}")


if __name__ == "__main__":
    main()
